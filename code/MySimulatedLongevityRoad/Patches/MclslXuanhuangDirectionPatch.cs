using System;
using System.Collections.Generic;
using System.Collections.Concurrent;
using System.IO;
using System.Linq;
using System.Runtime.CompilerServices;
using HarmonyLib;
using MySimulatedLongevityRoad.Core;
using MySimulatedLongevityRoad.Systems;
using MySimulatedLongevityRoad.Traits;
using UnityEngine;

namespace MySimulatedLongevityRoad.Patches;

internal static class MclslXuanhuangDirectionPatch
{
    // Resource dictionary root for the three facing directions (side/front/back).
    private const string ResourceRoot = "actors/species/civs/mclsl_xuanhuang";

    // Appearance variants: role (7 codes) x sex (2). 14 slots, matching the skin
    // names generated by AfterSprite ("female_1"/"male_1" plus a role suffix).
    private const int RoleNone=0,RoleZombie=1,RoleChild=2,RoleKing=3,RoleLeader=4,RoleWarrior=5,RoleOld=6;
    private const int SkinCount=14;

    private sealed class Facing
    {
        internal int Value; internal bool Left; internal AnimationFrameData Frame;
        // Per-actor resolve memo. It is invalidated whenever any input changes:
        // appearance (skin), faction colour, direction, animation kind and frame.
        // Packing all five into one value keeps the steady-state check to a single
        // comparison, with no path/composite string building and no lookups.
        internal long Signature=long.MinValue;
        internal Sprite Colored;
    }
    private sealed class Atlas
    {
        internal int Index;
        internal int Width,Height;
        internal Color32[] Pixels,Mask;
        internal string Path;
        internal MclslLivingResources.Group[] Groups;
    }
    // One resolved (direction, appearance) resource group. Immutable after Init.
    private sealed class Variant
    {
        internal int Index;
        internal Atlas Atlas;
        internal string Path;
        internal AnimationFrameData[] Frames;      // slot 0..3 walk, 4..7 swim
        internal Dictionary<string,int> SlotByName;
    }
    private static ConditionalWeakTable<Actor,Facing> Directions=new();
    private static readonly Dictionary<long,Texture2D> ColoredAtlases=new();
    // Per-nation recolour shade LUT, built once per colour (shared by all source
    // atlases of that colour). Cleared with the other per-world caches.
    private static readonly Dictionary<int,byte[]> NationShadeLuts=new();
    private static readonly ConcurrentDictionary<long,Sprite> ColoredFrames=new();
    private static readonly Dictionary<string,Atlas> Sources=new();
    private static readonly Dictionary<string,Variant> VariantsByPath=new();
    private static readonly Variant[,] VariantsByDirSkin=new Variant[3,SkinCount];
    private static readonly string[] SkinNames=new string[SkinCount];
    private sealed class ColorWork
    {
        internal int Key;
        internal Color32 Color;
        internal int Atlas;
    }
    private static readonly ConcurrentDictionary<int,byte> Colors=new();
    private static readonly Dictionary<int,ColorWork> Preparing=new();
    private static readonly Queue<ColorWork> ColorQueue=new();
    private static readonly ConcurrentDictionary<int,Color32> PendingColors=new();
    private static Atlas[] AtlasSources;
    private static bool _ready;

    internal static int Apply(Harmony harmony)
    {
        Init();
        int count=MclslHarmonyPatchGuard.TryPatch(harmony,"Actor.calculateMainSprite.xuanhuang-direction",
            AccessTools.Method(typeof(Actor),"calculateMainSprite"),null,
            AccessTools.Method(typeof(MclslXuanhuangDirectionPatch),nameof(AfterSprite)))?1:0;
        count+=MclslHarmonyPatchGuard.TryPatch(harmony,"Actor.getAnimationFrameData.xuanhuang",
            AccessTools.Method(typeof(Actor),"getAnimationFrameData"),null,
            AccessTools.Method(typeof(MclslXuanhuangDirectionPatch),nameof(AfterFrameData)))?1:0;
        count+=MclslHarmonyPatchGuard.TryPatch(harmony,"MapBox.preloadRenderedSprites.xuanhuang-colors",
            AccessTools.Method(typeof(MapBox),"preloadRenderedSprites"),
            AccessTools.Method(typeof(MclslXuanhuangDirectionPatch),nameof(BeforePreloadSprites)),null)?1:0;
        return count;
    }

    // Saved kingdoms need their colors before the loader asks for render frames,
    // which happens earlier than finishingUpLoading and its world-entry callback.
    private static void BeforePreloadSprites()=>PrepareWorldColors();

    // Faction colour is identified by packed RGB (alpha is ignored, matching the
    // previous string key). int keys avoid per-frame string allocation; the long
    // keys below pack composite dimensions without building path strings.
    private static int ColorCode(Color32 color)=>color.r<<16|color.g<<8|color.b;
    private static long AtlasColorKey(int atlasIndex,int colorCode)=>((long)atlasIndex<<32)|(uint)colorCode;
    private static long FrameKey(int variantIndex,int colorCode,int slot)=>((long)variantIndex<<32)|((long)colorCode<<8)|(uint)slot;
    // signature = colour(24b) << 9 | slot(3b) << 6 | dir(2b) << 4 | skin(4b)
    private static long Signature(int skin,int dir,int slot,int colorCode)
        =>((long)colorCode<<9)|((long)slot<<6)|((long)dir<<4)|(uint)skin;

    private static void Init()
    {
        if(!MclslRuntimeChanges.IsMainThread)throw new InvalidOperationException("Xuanhuang texture initialization requires the main thread.");
        if(_ready)return; // Immutable source pixels and variant metadata live for the mod's lifetime.
        string root=Path.Combine(MclslMod.I.GetDeclaration().FolderPath,"GameResources");
        foreach(string atlas in MclslLivingResources.Groups.Where(g=>g.Path.StartsWith(ResourceRoot,StringComparison.Ordinal)).Select(g=>g.Atlas).Distinct())
        {
            Color32[] Read(string suffix,out int width,out int height)
            {
                var texture=new Texture2D(2,2,TextureFormat.RGBA32,false);
                if(!ImageConversion.LoadImage(texture,File.ReadAllBytes(Path.Combine(root,atlas+suffix+".png")),false))
                    throw new InvalidDataException(atlas+suffix);
                width=texture.width;height=texture.height;
                Color32[] pixels=texture.GetPixels32();
                UnityEngine.Object.Destroy(texture);
                return pixels;
            }
            Color32[] pixels=Read("",out int width,out int height);
            Color32[] mask=Read("_robe_mask",out int maskWidth,out int maskHeight);
            if(width!=maskWidth||height!=maskHeight)throw new InvalidDataException("Robe mask dimensions: "+atlas);
            Sources.Add(atlas,new Atlas{Path=atlas,Width=width,Height=height,Pixels=pixels,Mask=mask,Groups=MclslLivingResources.Groups.Where(g=>g.Atlas==atlas).ToArray()});
        }
        // Pre-generate every static resource key (including the static Zombie skins)
        // once, so the draw path only indexes arrays instead of composing strings.
        foreach(var group in MclslLivingResources.Groups.Where(g=>Sources.ContainsKey(g.Atlas)))
        {
            var variant=new Variant{Index=VariantsByPath.Count,Atlas=Sources[group.Atlas],Path=group.Path,
                Frames=new AnimationFrameData[8],SlotByName=new Dictionary<string,int>(StringComparer.Ordinal)};
            foreach(var frame in group.Frames)
            {
                int slot=BaseFrameSlot(frame.Name);
                if(slot<0)continue; // head/item frames are never requested by AfterSprite
                variant.Frames[slot]=new AnimationFrameData {
                    id=frame.Name,sheet_path=group.Path,size_unit=new Vector2(frame.Width,frame.Height),
                    show_head=false,show_item=!frame.Name.StartsWith("swim_",StringComparison.Ordinal)
                        && !group.Path.EndsWith("/child",StringComparison.Ordinal)
                        && !group.Path.Contains("_child"),
                    pos_item=new Vector2((frame.ItemX-frame.PivotX)/frame.PixelsPerUnit,
                        (frame.ItemY-frame.PivotY)/frame.PixelsPerUnit)
                };
                variant.SlotByName[frame.Name]=slot;
            }
            VariantsByPath[group.Path]=variant;
        }
        for(int sex=0;sex<2;sex++)
        {
            string baseName=sex==1?"female_1":"male_1";
            for(int role=RoleNone;role<=RoleOld;role++)SkinNames[role*2+sex]=baseName+RoleSuffix(role);
        }
        string[] directionSuffix={"","_front","_back"};
        for(int dir=0;dir<3;dir++)
            for(int skin=0;skin<SkinCount;skin++)
                if(VariantsByPath.TryGetValue(ResourceRoot+directionSuffix[dir]+"/"+SkinNames[skin],out var resolved))
                    VariantsByDirSkin[dir,skin]=resolved;
        AtlasSources=Sources.Values.ToArray();
        for(int i=0;i<AtlasSources.Length;i++)AtlasSources[i].Index=i;
        _ready=true;
        PrepareWorldColors();
    }

    // Base walk/swim frame names are "walk_N"/"swim_N" with N in 0..3; the
    // "_head"/"_item" companions and longer names return -1.
    private static int BaseFrameSlot(string name)
    {
        if(name==null||name.Length!=6)return -1;
        bool swim=name.StartsWith("swim_",StringComparison.Ordinal);
        if(!swim&&!name.StartsWith("walk_",StringComparison.Ordinal))return -1;
        char digit=name[5];
        if(digit<'0'||digit>'3')return -1;
        int index=digit-'0';
        return swim?4+index:index;
    }

    private static string RoleSuffix(int role)=>role switch
    {
        RoleZombie=>"_zombie",RoleChild=>"_child",RoleKing=>"_king",RoleLeader=>"_leader",
        RoleWarrior=>"_warrior",RoleOld=>"_old",_=>""
    };

    private static int RoleIndex(Actor actor)
    {
        if(actor.asset.unit_zombie)return RoleZombie;
        if(actor.isBaby())return RoleChild;
        UnitProfession? profession=actor.profession_asset?.profession_id;
        if(profession==UnitProfession.King)return RoleKing;
        if(profession==UnitProfession.Leader)return RoleLeader;
        if(profession==UnitProfession.Warrior)return RoleWarrior;
        return actor.isPrettyOld()?RoleOld:RoleNone;
    }

    private static int SkinIndex(Actor actor)=>RoleIndex(actor)*2+(actor.isSexFemale()?1:0);

    private static Color32 NationColor(Actor actor)=>(actor.kingdom==null
        ?AssetManager.kingdoms.get("nomads_"+MclslXuanhuangRegistration.Id).default_kingdom_color
        :actor.kingdom.getColor()).getColorMainSecond();

    internal static void ObserveActor(Actor actor)
    {
        if(!_ready || actor?.asset==null || !Supported(actor))return;
        Color32 color=NationColor(actor);
        int key=ColorCode(color);
        if(!Colors.ContainsKey(key))PendingColors.TryAdd(key,color);
    }
    internal static void TickColors()
    {
        foreach(var entry in PendingColors)
        {
            if(!PendingColors.TryRemove(entry.Key,out var color) || Colors.ContainsKey(entry.Key)
                || Preparing.ContainsKey(entry.Key))continue;
            var work=new ColorWork{Key=entry.Key,Color=color};
            Preparing.Add(work.Key,work);ColorQueue.Enqueue(work);
        }
        while(ColorQueue.Count>0 && MclslFrameDeadline.RemainingMs>(MclslScheduler.HasFastWork?2d:0d))
        {
            var work=ColorQueue.Dequeue();
            if(Colors.ContainsKey(work.Key)){Preparing.Remove(work.Key);continue;}
            PrepareAtlas(AtlasSources[work.Atlas++],work.Color,work.Key);
            if(work.Atlas<AtlasSources.Length)ColorQueue.Enqueue(work);
            else {Preparing.Remove(work.Key);Colors.TryAdd(work.Key,0);}
        }
    }

    internal static void PrepareWorldColors()
    {
        if(!_ready || !MclslRuntimeChanges.IsMainThread)return;
        foreach(string id in new[]{MclslXuanhuangRegistration.Id,"nomads_"+MclslXuanhuangRegistration.Id})
            PrepareColor(AssetManager.kingdoms.get(id).default_kingdom_color.getColorMainSecond());
        string zombieKingdom=AssetManager.actor_library.get("zombie_"+MclslXuanhuangRegistration.Id).kingdom_id_wild;
        PrepareColor(AssetManager.kingdoms.get(zombieKingdom).default_kingdom_color.getColorMainSecond());
        if(World.world?.units!=null)
            foreach(var actor in World.world.units.getSimpleList())
                if(actor?.asset!=null && Supported(actor))
                    PrepareColor(NationColor(actor));
    }

    private static void PrepareColor(Color32 nation)
    {
        int color=ColorCode(nation);
        if(Colors.ContainsKey(color))return;
        if(Preparing.TryGetValue(color,out var work))
            while(work.Atlas<AtlasSources.Length)PrepareAtlas(AtlasSources[work.Atlas++],nation,color);
        else foreach(var source in AtlasSources)PrepareAtlas(source,nation,color);
        Colors.TryAdd(color,0);
    }

    private static void PrepareAtlas(Atlas source,Color32 nation,int colorCode)
    {
        // Reuse the coloured atlas for a (source atlas, colour) pair; only rebuild
        // when that input pair has not been produced yet.
        long atlasKey=AtlasColorKey(source.Index,colorCode);
        if(ColoredAtlases.ContainsKey(atlasKey))return;
        var pixels=(Color32[])source.Pixels.Clone();
        // Per-colour LUT, built once per nation and shared by every atlas of that
        // colour. The original derives shade exclusively from mask.r (the "robe
        // shade" channel) and applies it to all three output channels; shade only
        // has 256 possible values, so each output byte is fully determined by
        // mask.r. This is byte-exact to the previous per-pixel float math (same
        // truncate-to-byte), just faster and fetching from a cached table.
        if(!NationShadeLuts.TryGetValue(colorCode,out byte[] lut))
            NationShadeLuts[colorCode]=lut=BuildNationShadeLut(nation);
        for(int i=0;i<pixels.Length;i++)
        {
            if(source.Mask[i].a==0)continue;
            int shadeMask=source.Mask[i].r;
            byte r=lut[shadeMask];
            byte g=lut[256+shadeMask];
            byte b=lut[512+shadeMask];
            pixels[i]=new Color32(r,g,b,pixels[i].a);
        }
        var texture=new Texture2D(source.Width,source.Height,TextureFormat.RGBA32,false)
            {filterMode=FilterMode.Point,wrapMode=TextureWrapMode.Clamp};
        texture.SetPixels32(pixels);texture.Apply(false,true);
        ColoredAtlases.Add(atlasKey,texture);
        foreach(var group in source.Groups)
        {
            if(!VariantsByPath.TryGetValue(group.Path,out var variant))continue;
            foreach(var frame in group.Frames)
            {
                if(!variant.SlotByName.TryGetValue(frame.Name,out int slot))continue;
                var sprite=Sprite.Create(texture,new Rect(frame.X,frame.Y,frame.Width,frame.Height),
                    new Vector2(frame.PivotX/frame.Width,frame.PivotY/frame.Height),frame.PixelsPerUnit);
                sprite.name=frame.Name;MclslSpriteOwnership.Register(sprite);
                ColoredFrames.TryAdd(FrameKey(variant.Index,colorCode,slot),sprite);
            }
        }
    }

    /// <summary>
    /// 768-entry lookup of the recoloured RGB bytes for each possible mask-shade
    /// value <c>v</c> (0..255). Entry [ch*256+v] is the byte produced by
    /// <c>clamp(nation[ch]*(v/190f),0,255)</c> truncated to a byte — identical to
    /// the classic per-pixel formula, where <c>v</c> is the mask's red shade channel.
    /// </summary>
    private static byte[] BuildNationShadeLut(Color32 nation)
    {
        var lut=new byte[768];
        for(int v=0;v<256;v++)
        {
            float shade=v/190f;
            lut[v]      =(byte)Mathf.Clamp(nation.r*shade,0f,255f);
            lut[256+v]  =(byte)Mathf.Clamp(nation.g*shade,0f,255f);
            lut[512+v]  =(byte)Mathf.Clamp(nation.b*shade,0f,255f);
        }
        return lut;
    }

    internal static void Clear()
    {
        Directions=new();
        foreach(var sprite in ColoredFrames.Values)
        {MclslSpriteOwnership.Unregister(sprite);UnityEngine.Object.Destroy(sprite);}
        foreach(var texture in ColoredAtlases.Values)UnityEngine.Object.Destroy(texture);
        ColoredFrames.Clear();ColoredAtlases.Clear();NationShadeLuts.Clear();
        Colors.Clear();PendingColors.Clear();Preparing.Clear();ColorQueue.Clear();
    }

    private static void AfterSprite(Actor __instance,ref Sprite __result)
    {
        if(!Supported(__instance) || __result==null)return;
        Vector2 delta=Vector2.zero;
        if(__instance.is_moving)
            delta=__instance.next_step_position-__instance.current_position;
        else if(__instance.attack_target is Actor enemy && __instance.has_attack_target)
            delta=enemy.current_position-__instance.current_position;
        Facing facing=Directions.GetOrCreateValue(__instance);
        if(delta.sqrMagnitude>0.01f)
        {
            facing.Value=Math.Abs(delta.y)>Math.Abs(delta.x)*0.6f ? delta.y>0?2:1 : 0;
            if(Math.Abs(delta.x)>0.01f)facing.Left=delta.x<0;
        }
        // Native ActorRenderData reads Actor.flip; do not mirror the texture as well.
        __instance.setFlip(facing.Value==0 && facing.Left);
        int skin=SkinIndex(__instance);
        int dir=facing.Value;
        Variant variant=VariantsByDirSkin[dir,skin];
        if(variant==null)return; // unknown appearance/direction keeps the native frame
        // Swimming must be selected from the actual tile state, including shore
        // transitions where the native animation still returns its previous clip.
        bool swimming=__instance.isInWater();
        float speed=swimming?__instance.asset.animation_swim_speed:__instance.asset.animation_walk_speed;
        if(__instance.asset.animation_speed_based_on_walk_speed)
            speed=Mathf.Max(4f,speed*__instance.stats["speed"]/10f);
        int index=AnimationHelper.getSpriteIndex(AnimationHelper.getAnimationGlobalTime(speed),__instance.GetHashCode(),4);
        bool animate=__instance.isAlive()&&(__instance.is_moving||swimming);
        int slot=(swimming?4:0)+(animate?Mathf.Clamp(index,0,3):0);
        AnimationFrameData frame=variant.Frames[slot];
        if(frame==null)return;
        facing.Frame=frame;
        __instance.frame_data=frame;
        Color32 nation=NationColor(__instance);
        int colorCode=ColorCode(nation);
        long signature=Signature(skin,dir,slot,colorCode);
        if(facing.Signature==signature && !ReferenceEquals(facing.Colored,null))
        {
            MclslPerformanceProbe.RecordSpriteResolve(true);
            __result=facing.Colored;
            return;
        }
        if(ColoredFrames.TryGetValue(FrameKey(variant.Index,colorCode,slot),out var colored))
        {
            facing.Signature=signature;facing.Colored=colored;__result=colored;
            MclslPerformanceProbe.RecordSpriteResolve(true);
        }
        else
        {
            facing.Signature=signature;facing.Colored=null;
            PendingColors.TryAdd(colorCode,nation);
            MclslPerformanceProbe.RecordSpriteResolve(false);
        }
    }

    private static bool Supported(Actor actor)=>actor.asset.id==MclslXuanhuangRegistration.Id
        || actor.asset.id=="zombie_"+MclslXuanhuangRegistration.Id;

    private static void AfterFrameData(Actor __instance,ref AnimationFrameData __result)
    {
        if(Supported(__instance) && Directions.TryGetValue(__instance,out var facing) && facing.Frame!=null)
            __result=facing.Frame;
    }
}
